import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import copyStaticFiles from 'esbuild-copy-static-files';
import path from 'path';
import packageJson from './package.json' with { type: 'json' };

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Output always lands in ./dist/. Point a dev vault's plugin folder at it
// with a symlink.
const outdir = './dist/';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: [
		'main.ts',
		'styles.css',
	],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	// Matches tsconfig.json's target. esbuild lowers syntax only, so runtime
	// APIs newer than ES2020 are not polyfilled.
	target: 'es2020',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	minifySyntax: true,
	plugins: [
		copyStaticFiles({
			src: './manifest.json',
			dest: path.join(outdir, 'manifest.json'),
		}),
	],
	outdir: outdir,
	define: {
		'process.env.NODE_ENV': prod ? '"production"' : '"development"',
		'process.env.PLUGIN_VERSION': `'${ packageJson.version }'`,
		'process.env.EMULATE_MOBILE': prod
			? 'false'
			: process.argv.includes('--mobile').toString(),
	},
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
	await context.serve();
}
